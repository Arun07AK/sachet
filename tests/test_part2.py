def test_llm_tool_call_limited_to_three():
    requests = []

    def handler(request):
        body = json.loads(request.content)
        requests.append(body)
        if len(requests) == 1:
            return httpx.Response(200, json={"choices": [{"message": {"content": None,
                "tool_calls": [{"id": "1", "function": {"name": "web_search",
                "arguments": json.dumps({"query": COMPANY})}}]}}]})
        return httpx.Response(200, json={"choices": [{"message": {"content": '{"findings": []}'}}]})

    llm = LLM("https://llm.example/v1", "x", transport=httpx.MockTransport(handler))
    agent = Agent(SerpGateway(replay_dir=FIXTURES, cache_dir=None))
    agent.run(Offer("", company=COMPANY))
    assert llm.investigate(agent.last_investigation) == []
    assert len(requests) == 2
    assert requests[1]["messages"][-1]["role"] == "tool"


