def test_web_stream_report():
    async def check():
        app = create_app(replay_dir=FIXTURES)
        endpoint = next(route.endpoint for route in app.routes
                        if getattr(route, "path", None) == "/api/investigate")
        response = await endpoint(InvestigationRequest(text=f"Company: {COMPANY}\nRole: Analyst"))
        return [json.loads(line) async for line in response.body_iterator]

    events = asyncio.run(check())
    assert events[0]["type"] == "extracted"
    assert events[-1]["type"] == "report"
    assert "score" in events[-1]["report"]
    assert all("searches_left" in e for e in events if e["type"] == "step")


