def test_llm_investigate_and_planner_citation_filter():
    url = "https://kavera-analytics.in/careers"
    llm = mocked_llm({"content": "{}"}, {"content": json.dumps({"findings": [
        {"severity": "high", "title": "Cited", "detail": "Evidence", "source_urls": [url]},
        {"severity": "medium", "title": "Uncited", "detail": "No source", "source_urls": []},
        {"severity": "high", "title": "Invented", "detail": "Wrong", "source_urls": ["https://fake.test"]},
    ]})}, {"content": json.dumps({"summary": "Only a cited concern was found."})})
    report = Agent(SerpGateway(replay_dir=FIXTURES, cache_dir=None)).run(
        Offer("", company=COMPANY), llm=llm)
    assert [f.title for f in report.findings if f.origin == "llm"] == ["Cited"]
    assert report.dropped_llm_findings == 2
    assert report.to_dict()["dropped_llm_findings"] == 2
    assert report.summary == "Only a cited concern was found."


